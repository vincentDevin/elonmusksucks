/**
 * Domain Layer - Moderation Types
 *
 * Content moderation, user bans, and admin actions
 */

// ============================================================================
// Moderation Queue Types
// ============================================================================

/**
 * Moderation Queue Entry
 */
export interface ModerationQueueEntry {
  id: number;
  contentId: number;
  contentType: ModerationContentType;
  status: ModerationStatus;
  priority: ModerationPriority;
  flags: ModerationFlag[];
  submittedBy?: number; // userId who flagged
  assignedTo?: number; // moderator userId
  createdAt: Date;
  updatedAt: Date;
}

/**
 * Moderation Content Types
 */
export const ModerationContentType = {
  ARTICLE: 'article',
  PREDICTION: 'prediction',
  CONTENT: 'content', // Posts/comments
  MESSAGE: 'message', // Chat messages
  USER_PROFILE: 'user_profile',
} as const;

export type ModerationContentType =
  (typeof ModerationContentType)[keyof typeof ModerationContentType];

/**
 * Moderation Status
 */
export const ModerationStatus = {
  PENDING: 'pending',
  IN_REVIEW: 'in_review',
  APPROVED: 'approved',
  REJECTED: 'rejected',
  FLAGGED: 'flagged',
  ESCALATED: 'escalated',
} as const;

export type ModerationStatus =
  (typeof ModerationStatus)[keyof typeof ModerationStatus];

/**
 * Moderation Priority
 */
export const ModerationPriority = {
  LOW: 'low',
  NORMAL: 'normal',
  HIGH: 'high',
  URGENT: 'urgent',
} as const;

export type ModerationPriority =
  (typeof ModerationPriority)[keyof typeof ModerationPriority];

