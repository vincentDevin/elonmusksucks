export type WarningSeverity = (typeof WarningSeverity)[keyof typeof WarningSeverity];

// ============================================================================
// Moderation Reports
// ============================================================================

/**
 * Moderation Report
 */
export interface ModerationReport {
  id: string;
  period: {
    start: Date;
    end: Date;
  };
  stats: ModerationStats;
  actions: ModerationActionSummary[];
  topModerators: ModeratorPerformance[];
  generatedAt: Date;
}

/**
 * Moderation Statistics
 */
export interface ModerationStats {
  totalQueued: number;
  totalProcessed: number;
  approved: number;
  rejected: number;
  averageReviewTime: number; // milliseconds
  flagsReceived: number;
  autoFlags: number;
  userFlags: number;
  bansIssued: number;
  warningsIssued: number;
  mutesIssued: number;
}

/**
 * Moderation Action Summary
 */
export interface ModerationActionSummary {
  action: ModActionType;
  count: number;
  byContentType: Record<ModerationContentType, number>;
}

/**
 * Moderator Performance
 */
export interface ModeratorPerformance {
  moderatorId: number;
  moderatorName: string;
  actionsProcessed: number;
  averageReviewTime: number; // milliseconds
  accuracy?: number; // Percentage (if peer review enabled)
  specializations: ModerationContentType[];
}

// ============================================================================
// Auto-Moderation
// ============================================================================

/**
 * Auto-Moderation Rule
 */
export interface AutoModerationRule {
  id: string;
  name: string;
  description: string;
  enabled: boolean;
  contentType: ModerationContentType[];
  conditions: AutoModCondition[];
  action: AutoModAction;
  priority: number;
  createdBy: number;
  createdAt: Date;
}

/**
 * Auto-Moderation Condition
 */
export interface AutoModCondition {
  type: 'keyword' | 'regex' | 'length' | 'spam_score' | 'user_history';
  operator: 'contains' | 'matches' | 'equals' | 'greater_than' | 'less_than';
  value: string | number;
  caseSensitive?: boolean;
}

/**
 * Auto-Moderation Action
 */
export interface AutoModAction {
  type: 'flag' | 'auto_reject' | 'require_review' | 'shadow_hide';
  severity: FlagSeverity;
  notifyModerators: boolean;
  notifyUser?: boolean;
}

/**
 * Auto-Moderation Result
 */
export interface AutoModerationResult {
  triggered: boolean;
  rules: string[]; // Rule IDs that triggered
  action: AutoModAction;
  confidence: number; // 0-100
}
